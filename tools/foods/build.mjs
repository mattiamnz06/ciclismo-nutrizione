// Builds engine/FoodTable.kt from spec.txt and the USDA SR Legacy CSV export.
// Usage:
//   node build.mjs <usda-dir>                 build the Kotlin table
//   node build.mjs <usda-dir> search "a;b;!c"  list matching USDA descriptions
import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const [usda, mode, query] = process.argv.slice(2);
if (!usda) { console.error('usage: node build.mjs <usda-dir> [search <query>]'); process.exit(1); }

function parseCsvLine(line) {
  const out = []; let cur = ''; let q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (q) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (ch === '"') q = false;
      else cur += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

const foods = fs.readFileSync(path.join(usda, 'food.csv'), 'utf8').split(/\r?\n/).slice(1)
  .filter(Boolean).map(parseCsvLine).map(r => ({ id: r[0], desc: r[2] }));

function find(q) {
  if (q.startsWith('#')) return foods.filter(f => f.id === q.slice(1));
  const terms = q.toLowerCase().split(';').map(t => t.trim()).filter(Boolean);
  return foods.filter(f => {
    const d = f.desc.toLowerCase();
    return terms.every(t => t.startsWith('!') ? !d.includes(t.slice(1)) : d.includes(t));
  }).sort((a, b) => a.desc.length - b.desc.length);
}

if (mode === 'search') {
  for (const q of query.split('|')) {
    console.log(`== ${q}`);
    find(q).slice(0, 8).forEach(f => console.log(`  #${f.id} ${f.desc}`));
  }
  process.exit(0);
}

// Order of the micro columns written to the table.
const MICRO = ['iron', 'calcium', 'magnesium', 'potassium', 'sodium', 'zinc', 'vitC', 'vitD', 'vitE', 'b1', 'b2', 'b3', 'b6', 'folate', 'b12', 'omega3'];
const NUT = {
  1008: 'kcal', 1005: 'c', 1003: 'p', 1004: 'f', 1089: 'iron', 1087: 'calcium', 1090: 'magnesium', 1092: 'potassium',
  1093: 'sodium', 1095: 'zinc', 1162: 'vitC', 1114: 'vitD', 1109: 'vitE', 1165: 'b1', 1166: 'b2', 1167: 'b3',
  1175: 'b6', 1177: 'folate', 1178: 'b12', 1404: 'ala', 1270: 'pufa183', 1278: 'epa', 1272: 'dha', 1280: 'dpa',
};

const spec = fs.readFileSync(path.join(here, 'spec.txt'), 'utf8').split(/\r?\n/)
  .filter(l => l.trim() && !l.startsWith('#'));
const rows = [];
const wanted = new Map();
const missing = [];
for (const line of spec) {
  const manual = line.startsWith('@');
  const parts = (manual ? line.slice(1) : line).split('|');
  const [id, name, cat, piece, flags, allergens] = parts;
  const row = { id, name, cat, piece: piece || '0', liquid: (flags || '').includes('l'), allergens: allergens || '' };
  if (manual) {
    const [kcal, c, p, f] = parts[6].split(',').map(Number);
    const m = parts[7].split(',').map(Number);
    row.v = { kcal, c, p, f };
    MICRO.slice(0, 7).forEach((k, i) => { row.v[k] = m[i]; });
    row.source = 'manuale';
  } else {
    const hit = find(parts[6])[0];
    if (!hit) { missing.push(`${id}: ${parts[6]}`); continue; }
    row.fdc = hit.id; row.source = hit.desc;
    wanted.set(hit.id, {});
  }
  rows.push(row);
}
if (missing.length) { console.error('No match:\n  ' + missing.join('\n  ')); process.exit(2); }

const rl = readline.createInterface({ input: fs.createReadStream(path.join(usda, 'food_nutrient.csv')) });
for await (const line of rl) {
  const m = /^"\d+","(\d+)","(\d+)","([^"]*)"/.exec(line);
  if (!m || !wanted.has(m[1]) || !NUT[m[2]]) continue;
  wanted.get(m[1])[NUT[m[2]]] = Number(m[3]);
}

const r2 = x => Math.round(x * 100) / 100;
const lines = rows.map(row => {
  const v = row.v ?? wanted.get(row.fdc);
  if (!row.v) v.omega3 = (v.ala ?? v.pufa183 ?? 0) + (v.epa ?? 0) + (v.dha ?? 0) + (v.dpa ?? 0);
  const nums = [v.kcal, v.c, v.p, v.f, ...MICRO.map(k => v[k] ?? 0)].map(x => r2(x ?? 0));
  return [row.id, row.name, row.cat, row.piece, row.liquid ? 1 : 0, row.allergens.replaceAll(',', ' '), ...nums].join(';');
});

const kt = `package it.mattia.ciclismo.engine

// Generated by tools/foods/build.mjs from USDA FoodData Central SR Legacy (public domain). Do not edit by hand.
// Columns: id;name;category;piece g;liquid;allergens;kcal;carbs;protein;fat;${MICRO.join(';')} (per 100 g or ml).
internal const val FOOD_TABLE = """
${lines.join('\n')}
"""
`;
const out = path.join(here, '../../app/src/main/java/it/mattia/ciclismo/engine/FoodTable.kt');
fs.writeFileSync(out, kt);
fs.writeFileSync(path.join(here, 'sources.txt'), rows.map(r => `${r.id}\t${r.fdc ?? '-'}\t${r.source}`).join('\n') + '\n');
console.log(`${rows.length} foods written to ${path.relative(process.cwd(), out)}`);
